/**
 * Dashboard page controller: loads filter dropdowns, fetches aggregated
 * data from /api/dashboard_data.php for the current filter selection,
 * and renders the KPI cards, every chart, and every Top-10 leaderboard
 * (each with proportional-bar rows and a "See all" link to the full
 * ranking at ranking.html).
 *
 * Every panel renders independently: if one section's data failed on the
 * server (see api/dashboard_data.php's per-section error handling) or a
 * chart fails to draw client-side, that one panel shows an inline error
 * message instead of staying blank or breaking the rest of the page.
 */
(function () {
  const charts = {}; // name -> Chart instance

  // Chart.js defaults its text color to a dark gray meant for light
  // backgrounds; on this dark theme that reads as unreadable black text
  // (most visible on the doughnut legends). Overriding the global default
  // here means every chart — including legend text generated by custom
  // generateLabels() functions — starts from a readable light color.
  if (typeof Chart !== 'undefined') {
    Chart.defaults.color = '#93a3bd';
    Chart.defaults.borderColor = '#1a2740';
  }

  const CHART_PALETTE = ['#22d3c0', '#f5a623', '#f5646c', '#4ade80', '#7c9cf5', '#c084fc', '#5f7096'];

  // Maps each rank-list element id to the ranking.html dimension it drills into.
  const RANK_LIST_DIMS = {
    rankTechnicians: 'technician',
    rankSites: 'site',
    rankCategories: 'category',
    rankDepartments: 'department',
    rankRequesters: 'requester',
    rankOverdue: 'overdue_technician',
    rankFastest: 'technician_fastest',
    rankHighestRated: 'technician_highest_rated',
    rankLowestRated: 'requester_lowest_rated',
  };

  // These dims are per-technician — their name links to that technician's
  // profile page instead of the usual tickets.html drill-through, since
  // every technician name in the app is meant to link to their page. The
  // ticket count still links to tickets.html either way.
  const TECHNICIAN_DIMS = new Set(['technician', 'overdue_technician', 'technician_fastest', 'technician_highest_rated']);

  function baseChartOptions(extra = {}) {
    return Object.assign({
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: { labels: { color: '#93a3bd', font: { family: 'Inter', size: 11 } } },
      },
      scales: {
        x: { ticks: { color: '#5f7096' }, grid: { color: '#1a2740' } },
        y: { ticks: { color: '#5f7096' }, grid: { color: '#1a2740' }, beginAtZero: true },
      },
    }, extra);
  }

  /**
   * Makes a chart clickable: hovering a bar / slice / point shows a hand
   * cursor and the tooltip says so, and clicking opens tickets.html filtered
   * to exactly the rows that segment counted — the same filters currently
   * applied to the dashboard, plus whatever the segment itself means.
   *
   * `resolve(index, chart)` returns the extra filter params for the clicked
   * segment, or null when that segment has nothing to drill into.
   */
  function attachDrillThrough(options, resolve) {
    options.onHover = (event, elements) => {
      const target = event.native && event.native.target;
      if (target) target.style.cursor = elements.length ? 'pointer' : 'default';
    };
    options.onClick = (event, elements, chart) => {
      if (!elements.length) return;
      // datasetIndex matters on the multi-line charts, where the same x
      // position carries one point per series.
      const extra = resolve(elements[0].index, chart, elements[0].datasetIndex);
      if (!extra) return;
      DEMO.go(ITHub.ticketsLinkFor(extra));
    };

    options.plugins = options.plugins || {};
    options.plugins.tooltip = options.plugins.tooltip || {};
    options.plugins.tooltip.callbacks = options.plugins.tooltip.callbacks || {};
    if (!options.plugins.tooltip.callbacks.footer) {
      options.plugins.tooltip.callbacks.footer = () => 'Click to view these tickets';
    }
    return options;
  }

  /**
   * Shared doughnut config for Created By and Service vs Incident, so both
   * charts show the ticket count AND its percentage — in the legend text
   * itself, not only on hover — since a hover-only percentage is easy to
   * miss. Colors are positional (by palette order) by default, unless a
   * colorMap of { label: '#hex' } is passed, in which case that label
   * always gets that exact color regardless of its position in the data.
   */
  function buildDoughnutConfig(labels, values, colorMap = null, resolve = null) {
    const total = values.reduce((a, b) => a + Number(b), 0) || 1;
    const pct = (v) => ((Number(v) / total) * 100).toFixed(1);
    const colorFor = (label, i) => (colorMap && colorMap[label]) || CHART_PALETTE[i % CHART_PALETTE.length];
    const colors = labels.map((label, i) => colorFor(label, i));

    const config = {
      type: 'doughnut',
      data: {
        labels,
        datasets: [{ data: values, backgroundColor: colors, borderColor: '#131c2e', borderWidth: 2 }],
      },
      options: baseChartOptions({
        scales: undefined,
        plugins: {
          legend: {
            labels: {
              color: '#93a3bd',
              font: { family: 'Inter', size: 11 },
              generateLabels(chart) {
                return chart.data.labels.map((label, i) => ({
                  text: `${label}: ${Number(chart.data.datasets[0].data[i]).toLocaleString()} (${pct(chart.data.datasets[0].data[i])}%)`,
                  fillStyle: colors[i],
                  strokeStyle: '#131c2e',
                  fontColor: '#93a3bd',
                  index: i,
                }));
              },
            },
          },
          tooltip: {
            callbacks: {
              label(context) {
                const v = context.parsed;
                return `${context.label}: ${Number(v).toLocaleString()} (${pct(v)}%)`;
              },
            },
          },
        },
      }),
    };

    if (resolve) attachDrillThrough(config.options, resolve);
    return config;
  }

  /** Shows a small inline error message inside a chart's wrapper instead of leaving it blank. */
  function showChartError(canvasId, message) {
    const canvas = document.getElementById(canvasId);
    if (!canvas) return;
    const wrap = canvas.closest('.chart-wrap') || canvas.parentElement;
    wrap.innerHTML = `<div class="empty-state">Unavailable: ${ITHub.escapeHtml(message)}</div>`;
  }

  function renderOrUpdate(canvasId, config) {
    if (typeof Chart === 'undefined') {
      showChartError(canvasId, 'The Chart.js library did not load. Check that assets/js/vendor/chart.umd.js exists and is reachable.');
      return;
    }

    const canvas = document.getElementById(canvasId);
    if (!canvas) return;

    try {
      if (charts[canvasId]) {
        charts[canvasId].data = config.data;
        charts[canvasId].options = config.options;
        charts[canvasId].update();
        return;
      }
      charts[canvasId] = new Chart(canvas.getContext('2d'), config);
    } catch (err) {
      console.error(`Chart "${canvasId}" failed to render:`, err);
      showChartError(canvasId, err.message);
    }
  }

  // Maps each KPI label to the extra drill-through params for its tickets.html link.
  const KPI_LINK_PARAMS = {
    'Total Tickets':           {},
    'Overdue':                 { overdue: 'TRUE' },
    'First Response Overdue':  { first_response_overdue: 'TRUE' },
    'Reopened':                { reopened: 'TRUE' },
    'On-Time Rate':            { overdue: 'FALSE' },
    'Pending':                 { status: ['Pending'] },
    'On Hold':                 { status: ['On Hold'] },
    'VIP':                     { vip: 'TRUE' },
  };

  function renderKpis(kpis, errorMsg) {
    const grid = document.getElementById('kpiGrid');
    if (!grid) return;

    if (errorMsg) {
      grid.innerHTML = `<div class="empty-state">KPIs unavailable: ${ITHub.escapeHtml(errorMsg)}</div>`;
      return;
    }
    if (!kpis || kpis.length === 0) {
      grid.innerHTML = '<div class="empty-state">No data for the selected filters.</div>';
      return;
    }

    const accentFor = (label) => {
      if (/^overdue$|first response overdue/i.test(label)) return 'danger';
      if (/reopened|pending|on hold/i.test(label)) return 'warn';
      if (/on-time rate|^vip$/i.test(label)) return 'ok';
      return '';
    };

    grid.innerHTML = kpis.map(kpi => {
      const display = kpi.format === 'percent'
        ? `${Number(kpi.value).toLocaleString(undefined, { maximumFractionDigits: 1 })}%`
        : Number(kpi.value).toLocaleString();
      const href = ITHub.ticketsLinkFor(KPI_LINK_PARAMS[kpi.label] ?? {});
      return `
        <a class="kpi-card ${accentFor(kpi.label)}" href="${href}" title="View these tickets">
          <div class="kpi-label">${ITHub.escapeHtml(kpi.label)}</div>
          <div class="kpi-value">${display}</div>
        </a>
      `;
    }).join('');
  }

  /**
   * Renders a Top-10 list. Each row's background is tinted proportionally
   * to its value relative to the top row. For technician-dimension lists,
   * the name and the count are two separate links: the name goes to that
   * technician's profile page, the count always goes to tickets.html
   * showing exactly the tickets behind that row — clicking either does
   * something distinct and predictable.
   */
  function renderRankList(elementId, rows, errorMsg, dim) {
    const el = document.getElementById(elementId);
    if (!el) return;

    if (errorMsg) {
      el.innerHTML = `<li class="empty-state">Unavailable: ${ITHub.escapeHtml(errorMsg)}</li>`;
      return;
    }
    if (!rows || rows.length === 0) {
      el.innerHTML = '<li class="empty-state">No data</li>';
      return;
    }

    const max = Math.max(...rows.map(r => Number(r.value)), 1);
    const min = Math.min(...rows.map(r => Number(r.value)));
    const isTechDim = TECHNICIAN_DIMS.has(dim);
    // The SLA-speed list is ranked so that a SMALLER value is better; its
    // bar therefore has to fill towards the smallest value, otherwise the
    // fastest technician would draw the shortest bar.
    const lowerIsBetter = rows.some(r => r.lower_is_better);

    el.innerHTML = rows.map((r, i) => {
      const v = Number(r.value);
      const pct = lowerIsBetter
        ? Math.max(4, Math.round((min / (v || min || 1)) * 100))
        : Math.max(4, Math.round((v / max) * 100));
      const tint = `linear-gradient(to right, rgba(147,163,189,0.16) ${pct}%, transparent ${pct}%), var(--bg-panel-alt)`;
      const ticketsHref = ITHub.ticketsLinkFor(ITHub.rowDrillThroughParams(dim, r.label));
      const nameHref = isTechDim ? `technician.html?name=${encodeURIComponent(r.label ?? '')}` : ticketsHref;
      const valueText = r.display !== undefined ? ITHub.escapeHtml(r.display) : Number(r.value).toLocaleString();
      // Second line: what the headline number is actually made of
      // (average duration, share within SLA, ticket count).
      const meta = r.meta ? `<span class="rank-meta">${ITHub.escapeHtml(r.meta)}</span>` : '';
      return `
        <li class="rank-row" style="background:${tint};">
          <a class="rank-name-link" href="${nameHref}" title="${isTechDim ? 'View technician profile' : 'View these tickets'}">
            <span class="rank-index">${i + 1}</span> ${ITHub.escapeHtml(r.label ?? '—')}${meta}
          </a>
          <a class="rank-value-link" href="${ticketsHref}" title="View these tickets">${valueText}</a>
        </li>
      `;
    }).join('');
  }

  /** Points every "See all" button at ranking.html with the dimension + current filters. */
  function wireSeeAllLinks() {
    document.querySelectorAll('.see-all-link[data-dim]').forEach(btn => {
      btn.addEventListener('click', () => {
        const filters = ITHub.getFilterState();
        const params = ITHub.filtersToParams(filters, { dim: btn.dataset.dim });
        DEMO.go('ranking.html?' + params.toString());
      });
    });
  }

  function renderCharts(data, errors) {
    // Ticket volume — last 6 months.
    if (errors.monthly_trend || !data.monthly_trend) {
      showChartError('chartMonthly6', errors.monthly_trend || 'No data');
    } else {
      const monthlyRangeEl = document.getElementById('monthlyRangeLabel');
      if (monthlyRangeEl) monthlyRangeEl.textContent = data.monthly_trend.range_label || 'last 6 months';

      renderOrUpdate('chartMonthly6', {
        type: 'line',
        data: {
          labels: data.monthly_trend.labels,
          datasets: [{
            label: 'Tickets',
            data: data.monthly_trend.values,
            borderColor: CHART_PALETTE[0],
            backgroundColor: 'rgba(34,211,192,.15)',
            tension: 0.3,
            fill: true,
            pointRadius: 4,
            pointBackgroundColor: CHART_PALETTE[0],
          }],
        },
        options: attachDrillThrough(
          baseChartOptions({ plugins: { legend: { display: false } } }),
          // Clicking a month opens that month's tickets. The date range is
          // cleared because this chart deliberately ignores it.
          (i) => {
            const period = (data.monthly_trend.periods || [])[i];
            return period ? { months: [period], quarters: [], date_from: '', date_to: '' } : null;
          }
        ),
      });
    }

    // Created By — System vs Technician, as two lines over the same
    // 6-month window as the volume chart, so the relationship between them
    // is visible over time instead of as one flat total.
    if (errors.created_by_trend || !data.created_by_trend) {
      showChartError('chartCreatedBy', errors.created_by_trend || 'No data');
    } else {
      const trend = data.created_by_trend;
      const rangeEl = document.getElementById('createdByRangeLabel');
      if (rangeEl) rangeEl.textContent = trend.range_label || 'last 6 months';

      const line = (label, values, color, rgba) => ({
        label,
        data: values,
        borderColor: color,
        backgroundColor: rgba,
        tension: 0.3,
        fill: true,
        pointRadius: 4,
        pointBackgroundColor: color,
      });

      const datasets = [
        line('System', trend.system, CHART_PALETTE[0], 'rgba(34,211,192,.15)'),
        line('Technician', trend.technician, CHART_PALETTE[1], 'rgba(245,166,35,.12)'),
      ];
      // Only drawn when the data actually contains tickets with no creator.
      if (trend.unknown) {
        datasets.push(line('Unknown', trend.unknown, CHART_PALETTE[6], 'rgba(95,112,150,.12)'));
      }
      const KINDS = ['system', 'technician', 'unknown'];

      renderOrUpdate('chartCreatedBy', {
        type: 'line',
        data: { labels: trend.labels, datasets },
        options: attachDrillThrough(
          baseChartOptions(),
          // Clicking a point opens that month's tickets for that one series.
          (i, chart, datasetIndex) => {
            const period = (trend.periods || [])[i];
            const kind = KINDS[datasetIndex];
            return period && kind
              ? { months: [period], quarters: [], date_from: '', date_to: '', created_by_kind: kind }
              : null;
          }
        ),
      });
    }

    // Service vs Incident ratio — same visual family as Created By, but
    // with fixed, meaningful colors: Service is yellow, Incident is teal,
    // and anything else ("Other") is red.
    if (errors.service_incident || !data.service_incident) {
      showChartError('chartServiceIncident', errors.service_incident || 'No data');
    } else {
      const TYPE_GROUPS = { Service: 'service', Incident: 'incident', Other: 'other' };
      renderOrUpdate('chartServiceIncident', buildDoughnutConfig(
        data.service_incident.map(r => r.label ?? '—'),
        data.service_incident.map(r => r.value),
        { Service: '#f5a623', Incident: '#22d3c0', Other: '#f5646c' },
        (i) => {
          const g = TYPE_GROUPS[data.service_incident[i]?.label];
          return g ? { request_type_group: g } : null;
        }
      ));
    }

    // Group distribution — same visual style as Priority Distribution.
    if (errors.group_distribution || !data.group_distribution) {
      showChartError('chartGroups', errors.group_distribution || 'No data');
    } else {
      renderOrUpdate('chartGroups', {
        type: 'bar',
        data: {
          labels: data.group_distribution.map(r => r.label ?? '—'),
          datasets: [{ label: 'Tickets', data: data.group_distribution.map(r => r.value), backgroundColor: CHART_PALETTE[0], borderRadius: 6 }],
        },
        options: attachDrillThrough(
          baseChartOptions({ plugins: { legend: { display: false } } }),
          (i) => {
            const label = data.group_distribution[i]?.label;
            return label ? { ticket_group: [label] } : null;
          }
        ),
      });
    }

    // Ticket volume — by day, most recent month with data.
    if (errors.daily_trend || !data.daily_trend) {
      showChartError('chartDailyVolume', errors.daily_trend || 'No data');
    } else {
      const rangeLabelEl = document.getElementById('dailyVolumeMonthLabel');
      if (rangeLabelEl) rangeLabelEl.textContent = data.daily_trend.range_label || data.daily_trend.month_label || '';

      renderOrUpdate('chartDailyVolume', {
        type: 'line',
        data: {
          labels: data.daily_trend.labels,
          datasets: [{
            label: 'Tickets',
            data: data.daily_trend.values,
            borderColor: CHART_PALETTE[0],
            backgroundColor: 'rgba(34,211,192,.15)',
            tension: 0.3,
            fill: true,
            pointRadius: 3,
            pointBackgroundColor: CHART_PALETTE[0],
          }],
        },
        options: attachDrillThrough(
          baseChartOptions({ plugins: { legend: { display: false } } }),
          // One day = a from/to range of that single day; the Month and
          // Quarter selections are dropped so the day is not filtered away.
          (i) => {
            const day = (data.daily_trend.days || [])[i];
            return day ? { date_from: day, date_to: day, months: [], quarters: [] } : null;
          }
        ),
      });
    }

    // Priority distribution.
    if (errors.priority_distribution || !data.priority_distribution) {
      showChartError('chartPriority', errors.priority_distribution || 'No data');
    } else {
      renderOrUpdate('chartPriority', {
        type: 'bar',
        data: {
          labels: data.priority_distribution.map(r => r.label ?? '—'),
          datasets: [{
            label: 'Tickets',
            data: data.priority_distribution.map(r => r.value),
            backgroundColor: data.priority_distribution.map((r, i) => {
              const p = (r.label || '').toLowerCase();
              if (p === 'critical') return CHART_PALETTE[2];
              if (p === 'high') return CHART_PALETTE[1];
              if (p === 'medium') return CHART_PALETTE[6];
              if (p === 'low') return CHART_PALETTE[3];
              return CHART_PALETTE[i % CHART_PALETTE.length];
            }),
            borderRadius: 6,
          }],
        },
        options: attachDrillThrough(
          baseChartOptions({ plugins: { legend: { display: false } } }),
          (i) => {
            const label = data.priority_distribution[i]?.label;
            return label ? { priority: [label] } : null;
          }
        ),
      });
    }
  }

  async function loadDashboard() {
    try {
      const filters = ITHub.getFilterState();
      const params = ITHub.filtersToParams(filters);
      const data = await ITHub.fetchJSON('api/dashboard_data.php?' + params.toString());
      const errors = data.errors || {};

      renderKpis(data.kpis, errors.kpis);
      renderCharts(data, errors);
      renderRankList('rankTechnicians', data.top_technicians, errors.top_technicians, RANK_LIST_DIMS.rankTechnicians);
      renderRankList('rankSites', data.top_sites, errors.top_sites, RANK_LIST_DIMS.rankSites);
      renderRankList('rankCategories', data.top_categories, errors.top_categories, RANK_LIST_DIMS.rankCategories);
      renderRankList('rankDepartments', data.top_departments, errors.top_departments, RANK_LIST_DIMS.rankDepartments);
      renderRankList('rankRequesters', data.top_requesters, errors.top_requesters, RANK_LIST_DIMS.rankRequesters);
      renderRankList('rankOverdue', data.top_overdue, errors.top_overdue, RANK_LIST_DIMS.rankOverdue);
      renderRankList('rankFastest', data.top_fastest_technicians, errors.top_fastest_technicians, RANK_LIST_DIMS.rankFastest);
      renderRankList('rankHighestRated', data.top_rated_technicians, errors.top_rated_technicians, RANK_LIST_DIMS.rankHighestRated);
      renderRankList('rankLowestRated', data.lowest_rated_requesters, errors.lowest_rated_requesters, RANK_LIST_DIMS.rankLowestRated);

      if (Object.keys(errors).length > 0) {
        console.warn('Some dashboard sections failed to load:', errors);
      }
    } catch (err) {
      const grid = document.getElementById('kpiGrid');
      if (grid) grid.innerHTML = `<div class="empty-state">Failed to load dashboard data: ${ITHub.escapeHtml(err.message)}</div>`;
      console.error(err);
    }
  }

  document.addEventListener('DOMContentLoaded', async () => {
    ITHub.initAllMultiSelects();
    await ITHub.loadFilterMeta();
    ITHub.wireFilterButtons(loadDashboard);
    wireSeeAllLinks();
    await loadDashboard();
  });
})();
